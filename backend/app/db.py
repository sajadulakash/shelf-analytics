# ---------- Cross-process sync lock ----------
# The API (Instant Sync button) and the standalone worker can both decide to
# sync. Without a lock they would each claim the same unsynced rows and push
# them twice, since a row is only marked sent after the remote commits. A
# session-level advisory lock is held for the duration of a cycle and released
# automatically when the connection closes -- including if the process is killed.
SYNC_LOCK_KEY = 918273645


def try_sync_lock(conn) -> bool:
    """Take the sync lock, or return False if another process holds it."""
    with conn.cursor() as cur:
        cur.execute("SELECT pg_try_advisory_lock(%s)", (SYNC_LOCK_KEY,))
        return bool(cur.fetchone()[0])


def release_sync_lock(conn) -> None:
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT pg_advisory_unlock(%s)", (SYNC_LOCK_KEY,))
    except Exception:  # noqa: BLE001 - closing the connection releases it anyway
        pass


def sync_in_progress() -> bool:
    """True if any process is mid-cycle right now."""
    conn = connect(autocommit=True)
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT count(*) FROM pg_locks WHERE locktype = 'advisory' "
                "  AND classid = %s AND objid = %s AND granted",
                (SYNC_LOCK_KEY >> 32, SYNC_LOCK_KEY & 0xFFFFFFFF),
            )
            return int(cur.fetchone()[0]) > 0
    except Exception:  # noqa: BLE001
        return False
    finally:
        conn.close()


# ---------- Sync watermark ----------
def unsynced_batch(conn, limit: int) -> list[tuple]:
    """Next rows waiting to be sent, in the remote's column order.

    Rows with no id or no model_id are skipped: the remote requires model_id and
    the id is what makes a re-send safe, so those must be backfilled first
    (``python -m app.maintenance prepare-sync``).
    """
    with conn.cursor() as cur:
        cur.execute(
            "SELECT id, image_id, class_name, x_center, y_center, bbox_width, bbox_height, model_id "
            "  FROM product_detections "
            " WHERE synced_at IS NULL AND id IS NOT NULL AND model_id IS NOT NULL "
            " LIMIT %s",
            (limit,),
        )
        return cur.fetchall()


def mark_synced(conn, ids: list[str]) -> int:
    """Stamp synced_at on the rows that made it to the remote."""
    if not ids:
        return 0
    with conn.cursor() as cur:
        cur.execute(
            "UPDATE product_detections SET synced_at = now() WHERE id = ANY(%s)", (ids,)
        )
        updated = cur.rowcount
    if not conn.autocommit:
        conn.commit()
    return updated


def sync_counts() -> dict:
    """Backlog figures for the sync panel.

    ``pending`` deliberately counts only rows that *can* be sent; anything
    missing an id or a model_id is reported separately as blocked.
    """
    conn = connect(autocommit=True)
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT count(*) FILTER (WHERE synced_at IS NULL AND id IS NOT NULL "
                "                        AND model_id IS NOT NULL), "
                "       count(*) FILTER (WHERE synced_at IS NULL AND (id IS NULL "
                "                        OR model_id IS NULL)), "
                "       count(*) FILTER (WHERE synced_at IS NOT NULL) "
                "  FROM product_detections"
            )
            pending, blocked, synced = cur.fetchone()
            return {
                "pending": int(pending),
                "blocked": int(blocked),
                "synced": int(synced),
            }
    finally:
        conn.close()


def recent_activity(limit: int = 50) -> list[dict]:
    """Most recent per-image pipeline events, newest first (Runtime page)."""
    conn = connect(autocommit=True)
    try:
        with conn.cursor(cursor_factory=RealDictCursor) as cur:
            cur.execute(
                "SELECT i.image_id, i.status, i.rows_written, i.reason, i.updated_at, "
                "       i.job_id, j.source_filename "
                "  FROM data_dump_items i JOIN data_dump_jobs j USING (job_id) "
                " WHERE i.status <> 'pending' "
                " ORDER BY i.updated_at DESC LIMIT %s",
                (limit,),
            )
            return [dict(row) for row in cur.fetchall()]
    finally:
        conn.close()


def ledger_stats() -> dict:
    """Size of the dedup ledger, for the Runtime page header."""
    conn = connect(autocommit=True)
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT count(*) FROM image_inference_runs")
            return {"ledger_rows": int(cur.fetchone()[0])}
    finally:
        conn.close()
